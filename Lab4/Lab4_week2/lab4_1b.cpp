#include <iostream>
#include <cmath>
using namespace std;
int main(){
    cout << "abs of -2 = " << abs(-2) << endl;
    //หาค่าสัมบูรณ์ abs(-2) = 2     -2 → 2
    cout << "pow(2,3) = " << pow(2,3) << endl;
    //ยกกำลัง pow(2,3) = 8        2³ = 2 × 2 × 2 = 8
    cout << "sqrt(4) = " << sqrt(2) << endl;
    //หารากที่สอง sqrt(4) = 2     √4 = 2
    return (0);
}